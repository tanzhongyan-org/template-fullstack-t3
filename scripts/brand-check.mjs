#!/usr/bin/env node
// Brand gate: fails on forbidden defaults and broken brand wiring, and lists
// the TEMPLATE-BRAND slots a derived repo must fill (informational here).

import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const failures = [];

const walk = (dir, out = []) => {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
};

const scanDirs = ["src", "packages", ".storybook", "e2e", "public"]
  .map((d) => join(root, d))
  .flatMap((d) => {
    try {
      return walk(d);
    } catch {
      return [];
    }
  })
  .filter((f) => !f.includes("node_modules"));

// 1. Forbidden scaffold defaults. Tests assert the absence, so they are exempt.
const forbidden = ["Create T3 App", "Generated by create-t3-app", "create.t3.gg"];
for (const file of scanDirs.filter((f) => !/(\.test\.|\.spec\.)/.test(f))) {
  let text;
  try {
    text = readFileSync(file, "utf8");
  } catch {
    continue;
  }
  if (text.includes("\0")) continue;
  for (const phrase of forbidden) {
    if (text.includes(phrase)) {
      failures.push(`brand-check: ${file} still contains "${phrase}"`);
    }
  }
}

// 2. Hex colors outside the generated stylesheets.
for (const file of scanDirs.filter((f) => f.endsWith(".css") && !f.includes("generated"))) {
  const text = readFileSync(file, "utf8");
  const match = text.match(/#[0-9a-fA-F]{3}([0-9a-fA-F]{3})?\b/);
  if (match) failures.push(`brand-check: ${file} has a raw hex color ${match[0]}`);
}

// 3. Wiring: every surface reads the site config.
const exists = (rel) => {
  try {
    statSync(join(root, rel));
    return true;
  } catch {
    failures.push(`brand-check: missing ${rel}`);
    return false;
  }
};
for (const rel of [
  "src/app/icon.tsx",
  "src/app/apple-icon.tsx",
  "src/app/opengraph-image.tsx",
  "src/app/privacy/page.tsx",
  "src/app/terms/page.tsx",
  "src/app/refund/page.tsx",
  "src/app/sitemap.ts",
  "src/app/robots.ts",
  "src/styles/generated/tokens.css",
  "src/styles/generated/tokens.uniwind.css",
  ".storybook/main.ts",
  ".storybook/preview.tsx",
]) {
  exists(rel);
}
const layout = readFileSync(join(root, "src/app/layout.tsx"), "utf8");
if (!layout.includes("site.") || !layout.includes("shared/config/site")) {
  failures.push("brand-check: src/app/layout.tsx does not read the site config");
}
for (const rel of ["src/app/icon.tsx", "src/app/opengraph-image.tsx"]) {
  const text = readFileSync(join(root, rel), "utf8");
  if (!text.includes("site.")) failures.push(`brand-check: ${rel} does not read the site config`);
}

// 4. TEMPLATE-BRAND slots, informational in the template.
let slots = 0;
for (const file of scanDirs.filter((f) => /\.(ts|tsx)$/.test(f))) {
  const text = readFileSync(file, "utf8");
  const found = text.match(/TEMPLATE-BRAND\([a-z-]+\)/g);
  if (found) {
    slots += found.length;
    console.log(`brand-check: ${file} slots: ${[...new Set(found)].join(", ")}`);
  }
}
console.log(`brand-check: ${slots} TEMPLATE-BRAND slot(s) listed`);

if (failures.length > 0) {
  for (const failure of failures) console.error(failure);
  process.exit(1);
}
console.log("brand-check: wiring ok");
