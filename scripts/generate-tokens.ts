import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { type TokenName, tokens } from "../packages/shared/tokens";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src", "styles", "generated");
const webFile = join(outDir, "tokens.css");
const uniwindFile = join(outDir, "tokens.uniwind.css");

const header = `/* Generated by make tokens from packages/shared/tokens.ts. Do not edit by hand. */\n`;

const names = Object.keys(tokens) as TokenName[];
const block = (theme: "light" | "dark", indent: string): string =>
  names.map((n) => `${indent}--${n}: ${tokens[n][theme]};`).join("\n");

function webCss(): string {
  const light = block("light", "  ");
  const dark = block("dark", "  ");
  return `${header}:root {\n${light}\n}\n\n.dark {\n${dark}\n}\n`;
}

function uniwindCss(): string {
  const light = block("light", "      ");
  const dark = block("dark", "      ");
  return (
    `${header}@layer theme {\n  :root {\n    @variant light {\n${light}\n    }\n` +
    `    @variant dark {\n${dark}\n    }\n  }\n}\n`
  );
}

const checkOnly = process.argv.includes("--check");
mkdirSync(outDir, { recursive: true });
const outputs: Array<[string, string]> = [
  [webFile, webCss()],
  [uniwindFile, uniwindCss()],
];

let stale = false;
for (const [file, content] of outputs) {
  let current: string | null = null;
  try {
    current = readFileSync(file, "utf8");
  } catch {
    current = null;
  }
  if (current !== content) {
    if (checkOnly) {
      console.error(`tokens: ${file} is stale; run make tokens`);
      stale = true;
    } else {
      writeFileSync(file, content);
      console.log(`tokens: wrote ${file}`);
    }
  }
}
if (stale) process.exit(1);
if (checkOnly) console.log("tokens: generated files are fresh");
