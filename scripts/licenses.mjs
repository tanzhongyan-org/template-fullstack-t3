#!/usr/bin/env node
// License gate: every installed package must carry a permissive license.
// Fails on strong copyleft (GPL, AGPL, SSPL, EUPL, CC-BY-SA) and unknown
// licenses; weak copyleft (LGPL, MPL, EPL) needs an entry in EXCEPTIONS with
// an owner sign-off. Writes NOTICE with the full inventory.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const modulesDir = join(root, "node_modules");

/**
 * Weak-copyleft packages the owner explicitly allows: [name, reason].
 * Dev-only tools are exempt by policy and need no entry here.
 */
const EXCEPTIONS = [
  [
    "@img/sharp-win32-x64",
    "Next.js image optimizer; libvips stays LGPL because it is dynamically linked, never statically",
  ],
  [
    "@img/sharp-linux-x64",
    "Next.js image optimizer; libvips stays LGPL because it is dynamically linked, never statically",
  ],
  [
    "@img/sharp-linux-arm64",
    "Next.js image optimizer; libvips stays LGPL because it is dynamically linked, never statically",
  ],
  [
    "@img/sharp-darwin-x64",
    "Next.js image optimizer; libvips stays LGPL because it is dynamically linked, never statically",
  ],
  [
    "@img/sharp-darwin-arm64",
    "Next.js image optimizer; libvips stays LGPL because it is dynamically linked, never statically",
  ],
  ["sharp", "Next.js image optimizer; see the @img/sharp platform notes above"],
];

const FAIL = [/(?<!L)GPL/i, /\bSSPL\b/i, /EUPL/i, /CC-BY-SA/i, /Commons Clause/i];
const WARN = [/\bLGPL\b/i, /\bMPL\b/i, /\bEPL\b/i];

const licenseOf = (dir) => {
  const pkgFile = join(dir, "package.json");
  if (!existsSync(pkgFile)) return null;
  const pkg = JSON.parse(readFileSync(pkgFile, "utf8"));
  const declared = typeof pkg.license === "string" ? pkg.license : pkg.license?.type;
  if (declared) return { name: pkg.name, version: pkg.version, license: declared };
  // Fall back to a LICENSE file mention.
  const files = readdirSync(dir).filter((f) => /^licen[cs]e/i.test(f));
  if (files.length > 0) {
    const text = readFileSync(join(dir, files[0]), "utf8").slice(0, 400);
    const known = text.match(/MIT|Apache-2\.0|ISC|BSD|CC0|OFL|Unlicense/i);
    if (known) return { name: pkg.name, version: pkg.version, license: known[0] };
    return { name: pkg.name, version: pkg.version, license: "UNKNOWN (license file unread)" };
  }
  return { name: pkg.name, version: pkg.version, license: "UNKNOWN" };
};

const packages = [];
for (const entry of readdirSync(modulesDir)) {
  if (entry.startsWith(".")) continue;
  const full = join(modulesDir, entry);
  if (entry.startsWith("@")) {
    for (const child of readdirSync(full)) {
      const info = licenseOf(join(full, child));
      if (info) packages.push(info);
    }
  } else {
    const info = licenseOf(full);
    if (info) packages.push(info);
  }
}

const failures = [];
const warnings = [];

// Dev-only tools are exempt: a package reachable only through devDependencies
// never ships to users.
const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const closure = (seeds) => {
  const seen = new Set();
  const queue = [...seeds];
  while (queue.length > 0) {
    const name = queue.pop();
    if (!name || seen.has(name)) continue;
    seen.add(name);
    const dir = join(modulesDir, name);
    if (!existsSync(join(dir, "package.json"))) continue;
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    queue.push(...Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies }));
  }
  return seen;
};
const prodClosure = closure(Object.keys(manifest.dependencies ?? {}));
const devClosure = closure(Object.keys(manifest.devDependencies ?? {}));
const isDevOnly = (name) => devClosure.has(name) && !prodClosure.has(name);

for (const pkg of packages) {
  if (isDevOnly(pkg.name)) continue;
  if (FAIL.some((re) => re.test(pkg.license))) {
    failures.push(`${pkg.name}@${pkg.version}: ${pkg.license}`);
  } else if (pkg.license.startsWith("UNKNOWN")) {
    failures.push(`${pkg.name}@${pkg.version}: no recognizable license`);
  } else if (WARN.some((re) => re.test(pkg.license))) {
    const allowed = EXCEPTIONS.find(([name]) => name === pkg.name);
    if (allowed)
      warnings.push(`${pkg.name}@${pkg.version}: ${pkg.license} (exception: ${allowed[1]})`);
    else failures.push(`${pkg.name}@${pkg.version}: ${pkg.license} needs an owner exception`);
  }
}

packages.sort((a, b) => a.name.localeCompare(b.name));
const projectName = manifest.name ?? "this project";
writeFileSync(
  join(root, "NOTICE"),
  `Third-party licenses for ${projectName}.\nGenerated by make licenses; do not edit by hand.\n\n${packages.map((p) => `${p.name}@${p.version}: ${p.license}`).join("\n")}\n`,
);

for (const warning of warnings) console.log(`licenses: ${warning}`);
if (failures.length > 0) {
  for (const failure of failures) console.error(`licenses: FAIL ${failure}`);
  process.exit(1);
}
console.log(`licenses: ${packages.length} packages ok, NOTICE written`);
